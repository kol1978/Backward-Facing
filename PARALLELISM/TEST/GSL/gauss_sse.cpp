/*
 * Векторизованная квадратура Гаусса–Лежандра (SSE4.2)
 * В солвере XXXFoam могут быть места, где нужен быстрый интеграл с фиксированной точностью:
 * Интегрирование по толщине пограничного слоя — если функция гладкая, 8–16 узлов достаточно
 * Вычисление коэффициентов теплоотдачи из локальных профилей температуры
 * В этих случаях замена адаптивного GSL на фиксированную квадратуру с SSE4.2 даёт ускорение в 5–10 раз на одном ядре, потому что:
 * нет накладных расходов на адаптивность (аллокация workspace, рекурсия)
 * нет проверок ошибок и ветвлений
 * данные укладываются в кэш L1 (8 узлов + 8 весов = 128 байт)
 * Компиляция:
 *   gcc -O3 -msse4.2 gauss_legendre_sse.c -o gauss_legendre_sse
 *
 * Для твоего Xeon X5675:
 *   gcc -O3 -msse4.2 -march=westmere gauss_legendre_sse.c -o gauss_legendre_sse
 *
 * Проверка, поддерживает ли CPU SSE4.2:
 *   cat /proc/cpuinfo | grep sse4_2
 */

#include <stdio.h>
#include <math.h>
#include <xmmintrin.h>  /* SSE  */
#include <pmmintrin.h>  /* SSE3 (_mm_hadd_pd) */
#include <smmintrin.h>  /* SSE4.1 (_mm_dp_pd) */

/* ================================================================
 * ПРЕДВЫЧИСЛЕННЫЕ УЗЛЫ И ВЕСА GAUSS–LEGENDRE (8 точек, [-1, 1])
 * ================================================================
 *
 * 8 узлов выбраны по балансу точности и векторизации:
 * - SSE4.2 обрабатывает по 2 double (__m128d), 8 узлов = 4 шага
 * - Для f(x) = x^2 полином 2-й степени интегрируется ТОЧНО
 *   уже на 2 узлах; 8 узлов дают запас для сложных функций
 * - Полином степени до 15 интегрируется точно на 8 узлах
 *
 * Узлы и веса симметричны: t[0]=-t[7], w[0]=w[7] и т.д.
 * Храним только положительную половину для экономии,
 * но для векторизации удобнее хранить все 8 подряд.
 *
 * Источник: стандартные таблицы Абрамовица–Стегуна. */

/* Узлы на [-1, 1] */
static const double gl_nodes[8] = {
   -0.9602898564975363,   /* t0 */
   -0.7966664774136267,   /* t1 */
   -0.5255324099163290,   /* t2 */
   -0.1834346424956498,   /* t3 */
    0.1834346424956498,   /* t4 */
    0.5255324099163290,   /* t5 */
    0.7966664774136267,   /* t6 */
    0.9602898564975363    /* t7 */
};

/* Веса на [-1, 1] */
static const double gl_weights[8] = {
    0.1012285362903763,   /* w0 */
    0.2223810344533745,   /* w1 */
    0.3137066458778873,   /* w2 */
    0.3626837833783620,   /* w3 */
    0.3626837833783620,   /* w4 */
    0.3137066458778873,   /* w5 */
    0.2223810344533745,   /* w6 */
    0.1012285362903763    /* w7 */
};

/* ================================================================
 * ПОДЫНТЕГРАЛЬНАЯ ФУНКЦИЯ
 * ================================================================
 *
 * Та же f(x) = x^2, что и в GSL-примере.
 * Для векторизации критически важно, чтобы вычисление f
 * было «плоским» — без ветвлений, вызовов, рекурсии.
 * Компилятор развернёт это в SSE-инструкции автоматически
 * при -O3 -msse4.2, но мы также покажем ручной вариант. */

static inline double f_scalar(double x) {
    return x * x;
}

/* ================================================================
 * ВАРИАНТ 1: Автовекторизация (компилятор делает всё сам)
 * ================================================================
 *
 * Достаточно -O3 -msse4.2 — gcc развернёт цикл в SSE4.2.
 * Проверить: gcc -O3 -msse4.2 -fopt-info-vec-optimized
 * Если увидишь "loop vectorized" — всё работает. */

double integrate_auto(double a, double b) {
    /* Линейное отображение [-1,1] -> [a,b]:
     * x_i = (b-a)/2 * t_i + (b+a)/2
     * w_i' = (b-a)/2 * w_i
     * integral = sum(w_i' * f(x_i)) */

    const double half_len = 0.5 * (b - a);
    const double midpoint = 0.5 * (a + b);

    double sum = 0.0;
    for (int i = 0; i < 8; i++) {
        double x = half_len * gl_nodes[i] + midpoint;
        sum += gl_weights[i] * f_scalar(x);
    }
    return half_len * sum;
}

/* ================================================================
 * ВАРИАНТ 2: Ручная векторизация через SSE4.2 интринсики
 * ================================================================
 *
 * __m128d — 128-битный вектор из 2 double (регистр XMM).
 * На Xeon X5675 (Westmere) это родная ширина SIMD.
 *
 * Схема:
 * 1. Загружаем по 2 узла и 2 веса в XMM-регистры
 * 2. Масштабируем узлы: x = half_len * t + mid
 * 3. Вычисляем f(x) = x*x (двойное умножение)
 * 4. Умножаем на веса: w * f(x)
 * 5. Накапливаем сумму через _mm_add_pd
 * 6. В конце — горизонтальное сложение в один double
 *
 * 8 узлов / 2 = 4 итерации векторного цикла.
 * Для 16 узлов — 8 итераций, для 32 — 16. */

double integrate_sse(double a, double b) {
    /* Константы в виде __m128d (2 double в одном регистре) */
    /* half_len = (b-a)/2 — масштабирующий коэффициент */
    __m128d v_half_len = _mm_set1_pd(0.5 * (b - a));
    /* midpoint = (a+b)/2 — сдвиг центра */
    __m128d v_mid     = _mm_set1_pd(0.5 * (a + b));

    /* Аккумулятор: сумма w_i * f(x_i) в виде вектора из 2 double */
    __m128d v_acc = _mm_setzero_pd();

    /* --- Цикл по парам узлов ---
     * Шаг 0: узлы [0,1], веса [0,1]
     * Шаг 1: узлы [2,3], веса [2,3]
     * Шаг 2: узлы [4,5], веса [4,5]
     * Шаг 3: узлы [6,7], веса [6,7]
     *
     * _mm_load_pd загружает 2 выровненных double.
     * Массивы gl_nodes и gl_weights выровнены компилятором
     * автоматически (static const double), но для гарантии
     * можно добавить __attribute__((aligned(16))). */

    for (int i = 0; i < 8; i += 2) {
        /* Загружаем 2 узла: t[0..1] -> v_t */
        __m128d v_t = _mm_loadu_pd(&gl_nodes[i]);
        /* Загружаем 2 веса: w[0..1] -> v_w */
        __m128d v_w = _mm_loadu_pd(&gl_weights[i]);

        /* x = half_len * t + mid (линейное отображение)
         * _mm_mul_pd: покомпонентное умножение 2 double
         * _mm_add_pd: покомпонентное сложение */
        __m128d v_x = _mm_add_pd(
            _mm_mul_pd(v_half_len, v_t),
            v_mid
        );

        /* f(x) = x * x — покомпонентное возведение в квадрат */
        __m128d v_fx = _mm_mul_pd(v_x, v_x);

        /* w * f(x) — покомпонентное умножение на вес */
        __m128d v_wf = _mm_mul_pd(v_w, v_fx);

        /* Накапливаем: acc += w * f(x) */
        v_acc = _mm_add_pd(v_acc, v_wf);
    }

    /* --- Горизонтальное сложение ---
     * v_acc = [acc0, acc1] (2 double в одном регистре)
     * Нужно получить одно число: acc0 + acc1.
     *
     * _mm_hadd_pd(v_acc, v_acc) = [acc0+acc1, acc0+acc1]
     * Затем берём нижний элемент через _mm_cvtsd_f64. */
    __m128d v_sum = _mm_hadd_pd(v_acc, v_acc);
    double scalar_sum = _mm_cvtsd_f64(v_sum);

    /* Финальное умножение на half_len (т.к. веса тоже нужно масштабировать) */
    return (0.5 * (b - a)) * scalar_sum;
}

/* ================================================================
 * ВАРИАНТ 3: SSE4.1 _mm_dp_pd (dot product) — для сравнения
 * ================================================================
 *
 * _mm_dp_pd(a, b, mask) считает скалярное произведение
 * двух векторов с маской выбора элементов.
 * mask = 0xF1: умножить все 4 элемента (но у нас 2),
     * сложить, вернуть результат в нижний double.
     * Появилось в SSE4.1 (Nehalem/Westmere — есть). */

double integrate_sse4_dotprod(double a, double b) {
    __m128d v_half_len = _mm_set1_pd(0.5 * (b - a));
    __m128d v_mid      = _mm_set1_pd(0.5 * (a + b));

    /* Вектор узлов и весов, умноженных на f(x) */
    __m128d v_weighted_fx[4];

    for (int i = 0; i < 8; i += 2) {
        __m128d v_t = _mm_loadu_pd(&gl_nodes[i]);
        __m128d v_w = _mm_loadu_pd(&gl_weights[i]);

        __m128d v_x = _mm_add_pd(
            _mm_mul_pd(v_half_len, v_t), v_mid
        );
        __m128d v_fx = _mm_mul_pd(v_x, v_x);
        v_weighted_fx[i / 2] = _mm_mul_pd(v_w, v_fx);
    }

    /* Поэтапное скалярное произведение через _mm_dp_pd */
    __m128d v_acc = _mm_setzero_pd();
    for (int i = 0; i < 4; i++) {
        /* mask 0x31 = 0b00110001:
         *   биты [7:4] = 0b0011 — умножить элементы 0 и 1
         *   биты [3:0] = 0b0001 — вернуть в элемент 0 */
        v_acc = _mm_add_pd(v_acc, _mm_dp_pd(v_weighted_fx[i], _mm_set1_pd(1.0), 0x31));
    }

    return (0.5 * (b - a)) * _mm_cvtsd_f64(v_acc);
}

/* ================================================================
 * ОБОБЩЁННАЯ ВЕРСИЯ: произвольная функция через указатель
 * ================================================================
 *
 * Если f(x) — простая арифметика, компилятор может
 * инлайнить и векторизовать даже через указатель.
 * Но если f(x) содержит ветвления — векторизация сломается. */

double integrate_generic(double (*func)(double, void*), void *params,
                          double a, double b) {
    const double half_len = 0.5 * (b - a);
    const double midpoint = 0.5 * (a + b);

    double sum = 0.0;
    for (int i = 0; i < 8; i++) {
        double x = half_len * gl_nodes[i] + midpoint;
        sum += gl_weights[i] * func(x, params);
    }
    return half_len * sum;
}

/* ================================================================
 * MAIN: сравнение всех вариантов
 * ================================================================ */

int main(void) {
    const double a = 0.0;
    const double b = 1.0;
    const double exact = 1.0 / 3.0;  /* точное значение интеграла x^2 на [0,1] */

    printf("=== Квадратура Гаусса–Лежандра, 8 узлов, SSE4.2 ===\n");
    printf("Интеграл: x^2 на [%.1f, %.1f]\n", a, b);
    printf("Точное значение:  %.15f\n\n", exact);

    /* Вариант 1: автовекторизация */
    double r_auto = integrate_auto(a, b);
    printf("Автовекторизация:  %.15f  (погрешность: %.2e)\n",
           r_auto, fabs(r_auto - exact));

    /* Вариант 2: ручные SSE4.2 интринсики */
    double r_sse = integrate_sse(a, b);
    printf("SSE4.2 intrinsics: %.15f  (погрешность: %.2e)\n",
           r_sse, fabs(r_sse - exact));

    /* Вариант 3: SSE4.1 dot product */
    double r_dp = integrate_sse4_dotprod(a, b);
    printf("SSE4.1 dp_pd:      %.15f  (погрешность: %.2e)\n",
           r_dp, fabs(r_dp - exact));

    /* Обобщённая версия через указатель */
    double r_gen = integrate_generic(
        (double (*)(double, void*))f_scalar, NULL, a, b
    );
    printf("Generic (ptr):     %.15f  (погрешность: %.2e)\n",
           r_gen, fabs(r_gen - exact));

    printf("\nВсе результаты должны совпадать с точностью до ошибки округления.\n");

    return 0;
}
